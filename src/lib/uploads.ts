/** Extensions the admin can pick: the stored formats plus CBR, which the browser converts to CBZ before uploading. */
export const pickExtensions = (kind: 'comic' | 'anime') => (kind === 'comic' ? ['cbz', 'cbr', 'pdf'] : Object.keys(UNIT_FORMATS[kind]));
export const formatList = (kind: 'comic' | 'anime') => pickExtensions(kind).map((f) => f.toUpperCase()).join(', ').replace(/, (\w+)$/, ' o $1');
export const MAX_UNIT_NUMBER = 99999;
export const isUnitNumber = (n: unknown): n is number => Number.isInteger(n) && (n as number) >= 0 && (n as number) <= MAX_UNIT_NUMBER;

/**
 * Labels look like "<series> #5" or "<series> - Episodio 5", so an uploaded file joins the
 * unit that already exists with that label. The series defaults to the title.
 */
export const unitLabel = (media: { title: string; kind: string }, n: number, series?: unknown) => {
  const name = (typeof series === 'string' && series.trim() ? series.trim() : media.title).slice(0, 150);
  return media.kind === 'anime' ? `${name} - Episodio ${n}` : `${name} #${n}`;
};

export const formatBytes = (n: number) =>
  n < 1024 * 1024 ? `${Math.max(1, Math.round(n / 1024))} KB` : n < 1024 ** 3 ? `${(n / 1024 / 1024).toFixed(1)} MB` : `${(n / 1024 ** 3).toFixed(2)} GB`;

/** "CBZ · 32.0 MB" from a stored file's format and size. */
export const fileMeta = (format: string | null, size: number | null) => {
  const name = format?.toUpperCase() ?? 'Archivo';
  return size ? `${name} · ${formatBytes(size)}` : name;
};

/** fileMeta for a unit with a file, "Sin archivo" otherwise. */
export const unitFileMeta = (unit: { file_path: string | null; file_format: string | null; file_size: number | null } | null) =>
  unit?.file_path ? fileMeta(unit.file_format, unit.file_size) : 'Sin archivo';

/** Comics are stored as one image per page inside a folder per issue, so the reader loads only what is read. */
export const PAGE_TYPES: Record<string, string> = { jpg: 'image/jpeg', jpeg: 'image/jpeg', png: 'image/png', webp: 'image/webp', gif: 'image/gif', avif: 'image/avif' };
export const PAGE_MAX_BYTES = 50 * 1024 * 1024;
export const MAX_PAGES = 2000;
/** Page file names are generated by the uploader: "001.jpg", "0012.webp"… never a path. */
export const isPageName = (name: unknown): name is string => typeof name === 'string' && /^\d{3,4}\.[a-z]{3,4}$/.test(name) && extensionOf(name) in PAGE_TYPES;
export const unitFolder = (slug: string, n: number, stamp = Date.now()) => `${slug}/${String(n).padStart(5, '0')}-${stamp}/`;

/** Validates the page list the browser wants to upload. */
export function checkPages(pages: unknown): { pages: { name: string; content_type: string; size: number }[] } | { error: string } {
  if (!Array.isArray(pages) || pages.length === 0) return { error: 'El cómic no tiene páginas.' };
  if (pages.length > MAX_PAGES) return { error: `Un número puede tener hasta ${MAX_PAGES} páginas.` };
  const seen = new Set<string>();
  for (const p of pages) {
    if (!isPageName(p?.name) || typeof p.size !== 'number' || p.size <= 0) return { error: 'Cada página debe ser una imagen (JPG, PNG, WEBP, GIF o AVIF).' };
    if (p.size > PAGE_MAX_BYTES) return { error: 'Una página pesa más de 50 MB.' };
    if (seen.has(p.name)) return { error: `Página repetida: ${p.name}.` };
    seen.add(p.name);
  }
  return { pages: pages.map((p) => ({ name: p.name, content_type: PAGE_TYPES[extensionOf(p.name)], size: p.size })) };
}

/** Every file directly inside `folder` with its size (Storage lists at most 1000 per call). */
export async function listFolder(sb: SupabaseClient, bucket: string, folder: string) {
  const files = new Map<string, number>();
  const dir = folder.replace(/\/$/, '');
  for (let offset = 0; ; offset += 1000) {
    const { data, error } = await sb.storage.from(bucket).list(dir, { limit: 1000, offset, sortBy: { column: 'name', order: 'asc' } });
    if (error) throw error;
    (data ?? []).forEach((f) => files.set(f.name, Number(f.metadata?.size ?? 0)));
    if (!data || data.length < 1000) return files;
  }
}

/** Deletes what a unit had stored: its single file, or every listed page of its folder. */
export async function removeStored(sb: SupabaseClient, unit: { file_path: string | null; pages?: string[] | null }) {
  if (!unit.file_path) return;
  const paths = unit.pages ? unit.pages.map((p) => `${unit.file_path}${p}`) : [unit.file_path];
  for (let i = 0; i < paths.length; i += 1000) {
    const { error } = await sb.storage.from('content').remove(paths.slice(i, i + 1000));
    if (error) throw error;
  }
}

/** Runs `fn` over `items` with at most `limit` running at once, keeping the order of results. */
export async function mapLimit<T, R>(items: T[], limit: number, fn: (item: T) => Promise<R>) {
  const out: R[] = new Array(items.length);
  let next = 0;
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, async () => {
    while (next < items.length) { const i = next++; out[i] = await fn(items[i]); }
  }));
  return out;
}

